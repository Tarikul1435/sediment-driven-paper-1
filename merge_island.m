% 1.30 = 30% larger
% 1.50 = 50% larger
% 0.90 = 10% smaller
% 0.80 = 20% smaller
%
% ???????? independently change ??? ?????
%% ============================================================

ur_scale = 1.70;       % URIR CHAR
sw_scale = 1.50;       % SANDWIP
sd_scale = 1.60;       % SWARNA DWIP
bc_scale = 2.5;       % BHASHAN CHAR


%% ============================================================
% FIGURE
%% ============================================================

figure('Color','w',...
       'Position',[50 50 1200 800]);


%% ============================================================
% LOOP THROUGH YEARS
%% ============================================================

for s = 1:num_steps

    subplot(3,3,s);
    hold on;


    %% ========================================================
    % COMMON GROWTH SCALE
    %% ========================================================

    scale = steps(s);


    %% ========================================================
    % URIR CHAR
    %
    % Individual size controlled by ur_scale
    %% ========================================================

    urx = (lon_ur-lonc_ur) ...
          * scale * ur_scale + lonc_ur;

    ury = (lat_ur-latc_ur) ...
          * scale * ur_scale + latc_ur + 0.04;


    %% ========================================================
    % SANDWIP
    %
    % Individual size controlled by sw_scale
    %% ========================================================

    swx = (lon_sw-lonc_sw) ...
          * scale * sw_scale + lonc_sw;

    swy = (lat_sw-latc_sw) ...
          * scale * sw_scale + latc_sw;


    %% ========================================================
    % SWARNA DWIP
    %
    % Individual size controlled by sd_scale
    %% ========================================================

    sdx = (lon_sd-lonc_sd) ...
          * scale * sd_scale + lonc_sd;

    sdy = (lat_sd-latc_sd) ...
          * scale * sd_scale + latc_sd;


    %% ========================================================
    % BHASHAN CHAR
    %
    % Individual size controlled by bc_scale
    %% ========================================================

    bcx = (lon_bc-lonc_bc) ...
          * scale * bc_scale + lonc_bc;

    bcy = (lat_bc-latc_bc) ...
          * scale * bc_scale + latc_bc;


    %% ========================================================
    % COMBINED ISLAND MASK
    %% ========================================================

    mask = inpolygon(X,Y,urx,ury) | ...
           inpolygon(X,Y,swx,swy) | ...
           inpolygon(X,Y,sdx,sdy) | ...
           inpolygon(X,Y,bcx,bcy);


    %% ========================================================
    % SMOOTHING
    %% ========================================================

    density = imgaussfilt(double(mask),5);


    %% ========================================================
    % DISPLAY
    %% ========================================================

    imagesc(x,y,density);

    set(gca,'YDir','normal');


    %% ========================================================
    % COLORMAP
    %% ========================================================

    colormap([ ...
        0   0   0.5
        0   0   1
        0   0.8 1
        1   0   0
        0.5 0   0]);


    caxis([0 1]);


