22.452834,...
22.431906,...
22.418435,...
22.402684,...
22.398538,...
22.399367,...
22.407244,...
22.421544,...
22.434600,...
22.439159,...
22.447240,...
22.462987,...
22.483910,...
22.512080,...
22.525541,...
22.548112,...
22.575233,...
22.594691,...
22.606903];

%% ORIGINAL LONGITUDE DATA
lon = [...
91.445492,...
91.450500,...
91.456500,...
91.461336,...
91.467500,...
91.474644,...
91.488500,...
91.502845,...
91.512000,...
