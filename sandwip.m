91.457335,...
91.443659,...
91.435364,...
91.428638,...
91.427517,...
91.432001,...
91.430432,...
91.432674,...
91.440745];

%% CHECK DATA LENGTH
if length(lat) ~= length(lon)
    error('Latitude and longitude arrays must have the same length.');
end

%% CLOSE THE BOUNDARY
if lat(1) ~= lat(end) || lon(1) ~= lon(end)
    lat = [lat lat(1)];
    lon = [lon lon(1)];
end

%% REMOVE CONSECUTIVE DUPLICATE POINTS
keep = [true, ...
    (diff(lat).^2 + diff(lon).^2) > 1e-12];

lat = lat(keep);
lon = lon(keep);

%% PERIODIC PARAMETER
t = 1:length(lat);

%% SMOOTH CLOSED SPLINE
t_fine = linspace(1,length(lat),N);

if exist('csape','file') == 2

    pp_lon = csape(t,lon,'periodic');
    pp_lat = csape(t,lat,'periodic');

    lon0 = fnval(pp_lon,t_fine);
    lat0 = fnval(pp_lat,t_fine);

else

    warning(['csape was not found. Using pchip interpolation ' ...
             'instead.']);

    lon0 = pchip(t,lon,t_fine);
    lat0 = pchip(t,lat,t_fine);

end

%% FORCE EXACT CLOSURE
lon0(end) = lon0(1);
lat0(end) = lat0(1);

%% CONVERT LATITUDE-LONGITUDE TO LOCAL KM
lat_ref = mean(lat0);

km_per_degree_lat = 111.32;
km_per_degree_lon = 111.32*cosd(lat_ref);

lon_ref_base = mean(lon0);
lat_ref_base = mean(lat0);

x0 = (lon0-lon_ref_base)*km_per_degree_lon;
y0 = (lat0-lat_ref_base)*km_per_degree_lat;

%% BASE AREA
baseArea = polyarea(x0,y0);

%% DISPLAY BASE INFORMATION
fprintf('\n');
fprintf('=============================================\n');
fprintf('         SANDWIP COASTLINE MODEL\n');
fprintf('=============================================\n');

fprintf('Number of control points = %d\n',length(lat));
fprintf('Number of smooth points  = %d\n',N);
fprintf('Reference Longitude = %.6f deg E\n',lon_ref_base);
fprintf('Reference Latitude  = %.6f deg N\n',lat_ref_base);
fprintf('Base Area = %.4f km^2\n',baseArea);

fprintf('=============================================\n');

%% AREA SCALING FACTORS
S1960 = 1.00*sqrt(A1960/baseArea);
S1990 = 1.01*sqrt(A1990/baseArea);
S2020 = 1.04*sqrt(A2020/baseArea);
S2050 = 1.07*sqrt(A2050/baseArea);

%% REFERENCE LOCATION
lon_ref = mean(lon0);
lat_ref = mean(lat0);

%% 1960 BOUNDARY
x1960 = S1960*x0;
y1960 = S1960*y0;

lon1960 = lon_ref+x1960/(111.32*cosd(lat_ref));
lat1960 = lat_ref+y1960/111.32;

%% 1990 BOUNDARY
x1990 = S1990*x0;
y1990 = S1990*y0;

lon1990 = lon_ref+x1990/(111.32*cosd(lat_ref));
lat1990 = lat_ref+y1990/111.32;

%% 2020 BOUNDARY
x2020 = S2020*x0;
y2020 = S2020*y0;

lon2020 = lon_ref+x2020/(111.32*cosd(lat_ref));
lat2020 = lat_ref+y2020/111.32;

%% 2050 PREDICTED BOUNDARY
x2050 = S2050*x0;
y2050 = S2050*y0;

lon2050 = lon_ref+x2050/(111.32*cosd(lat_ref));
lat2050 = lat_ref+y2050/111.32;

%% VERIFY AREAS
area1960 = polyarea(x1960,y1960);
area1990 = polyarea(x1990,y1990);
area2020 = polyarea(x2020,y2020);
area2050 = polyarea(x2050,y2050);

%% DISPLAY CALCULATED AREAS
fprintf('\n');
fprintf('=============================================\n');
fprintf('             CALCULATED AREAS\n');
fprintf('=============================================\n');

fprintf('1960 = %.2f km^2\n',area1960);
fprintf('1990 = %.2f km^2\n',area1990);
fprintf('2020 = %.2f km^2\n',area2020);
fprintf('2050 = %.2f km^2\n',area2050);

fprintf('=============================================\n');

%% COMBINE ALL BOUNDARIES
allLon = [lon1960,lon1990,lon2020,lon2050];
allLat = [lat1960,lat1990,lat2020,lat2050];

%% AXIS MARGINS - 15 PERCENT
lon_margin = 0.35*(max(allLon)-min(allLon));
lat_margin = 0.15*(max(allLat)-min(allLat));

lon_min = min(allLon)-lon_margin;
lon_max = max(allLon)+lon_margin;

lat_min = min(allLat)-lat_margin;
lat_max = max(allLat)+lat_margin;

%% CREATE FIGURE
figure(...
    'Color','white',...
    'Position',[100 100 1200 750],...
    'Name','Sandwip Island Coastline Evolution');

hold on;

%% LIGHT GREEN LAND FILL
fill(lon1960,lat1960,...
    [0.91 0.96 0.86],...
    'EdgeColor','none',...
    'HandleVisibility','off');

%% 1960 COASTLINE - GREEN
h1960 = plot(lon1960,lat1960,...
    'Color',[0 0.55 0],...
    'LineWidth',2.2,...
    'LineStyle','-');

%% 1990 COASTLINE - BLUE
h1990 = plot(lon1990,lat1990,...
    'Color',[0 0.35 0.85],...
    'LineWidth',2.2,...
    'LineStyle','-');

%% 2020 COASTLINE - PURPLE
h2020 = plot(lon2020,lat2020,...
    'Color',[0.75 0 0.75],...
    'LineWidth',2.2,...
    'LineStyle','-');

%% 2050 PREDICTED COASTLINE - RED
h2050 = plot(lon2050,lat2050,...
    'Color',[1 0 0],...
    'LineWidth',2.5,...
    'LineStyle','-');

%% ISLAND NAME
text(lon_ref,lat_ref,'Sandwip',...
    'HorizontalAlignment','center',...
    'VerticalAlignment','middle',...
    'FontSize',20,...
    'FontWeight','bold',...
    'FontName','Times New Roman');

%% LEGEND INSIDE THE GRAPH
lgd = legend([h1960 h1990 h2020 h2050],{...
    'Sandwip - 1960 (220 km^2)',...
    'Sandwip - 1990 (245 km^2)',...
    'Sandwip - 2020 (256 km^2)',...
    'Sandwip - 2050 (Predicted: 264.14 km^2)'},...
    'Location','northeast',...
    'FontSize',15,...
    'FontName','Times New Roman',...
    'Box','on');

set(lgd,'Color','white');

%% AXIS LABELS
xlabel('Longitude (^oE)',...
    'FontSize',13,...
    'FontWeight','bold',...
    'FontName','Times New Roman');

ylabel('Latitude (^oN)',...
    'FontSize',13,...
    'FontWeight','bold',...
    'FontName','Times New Roman');



%% GRID AND BOX
grid on;
box on;

%% EQUAL GEOGRAPHIC SCALE
axis equal;

%% AXIS APPEARANCE
set(gca,...
    'FontSize',11,...
    'LineWidth',1.2,...
    'Layer','top',...
    'FontName','Times New Roman');

%% AXIS LIMITS
xlim([lon_min lon_max]);
ylim([lat_min lat_max]);

%% LONGITUDE TICKS
xticks(floor(lon_min*100)/100:0.02:ceil(lon_max*100)/100);

%% LATITUDE TICKS
yticks(floor(lat_min*100)/100:0.02:ceil(lat_max*100)/100);

%% TICK FORMAT
xtickformat('%.2f');
ytickformat('%.2f');

%% FINISH
hold off;

fprintf('\nSandwip coastline plot completed.\n');
