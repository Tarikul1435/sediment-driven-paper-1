
clc;
clear;
close all;

%% =========================================================
% SANDWIP ISLAND COASTLINE EVOLUTION
% EXTRA-SMOOTH AND ROUNDED TOP BOUNDARY
% 2050 PREDICTED AREA = 264.14 km^2
% LEGEND INSIDE THE GRAPH
%% =========================================================

%% TARGET AREAS
A1960 = 220.00;
A1990 = 245.00;
A2020 = 256.00;
A2050 = 264.14;

%% NUMBER OF SMOOTH BOUNDARY POINTS
N = 3000;

%% ORIGINAL LATITUDE DATA
lat = [...
22.608595,...
22.606800,...
22.601200,...
22.597894,...
22.592500,...
22.587240,...
22.572500,...
22.557980,...
22.548500,...
